CZstdDict::CZstdDict()
{
	m_pCompressContext = 0x0;
	m_pDecompressContext = 0x0;
}

CZstdDict::~CZstdDict()
{
	if(m_pCompressContext)
		ZSTD_freeCCtx(m_pCompressContext);
	if(m_pDecompressContext)
		ZSTD_freeDCtx(m_pDecompressContext);
}

void CZstdDict::LoadDictionary()
{
	if(m_pCompressContext)
		ZSTD_CCtx_loadDictionary(m_pCompressContext, s_aDictionary, sizeof(s_aDictionary));
	if(m_pDecompressContext)
		ZSTD_DCtx_loadDictionary(m_pDecompressContext, s_aDictionary, sizeof(s_aDictionary));
}

void CZstdDict::Init()
{
	m_pCompressContext = ZSTD_createCCtx();
	m_pDecompressContext = ZSTD_createDCtx();
	LoadDictionary();
}

int CZstdDict::Compress(const void *pInput, int InputSize, void *pOutput, int OutputSize)
{
	if(!m_pCompressContext || InputSize <= 0 || OutputSize <= 0)
		return -1;

	// Level 3 is the zstd default and the measured sweet spot here: with a
	// dictionary the level barely changes the ratio (see the benchmark test),
	// while a higher level only costs CPU. The dictionary itself stays loaded
	// across calls, ZSTD_reset_session_only keeps it.
	ZSTD_CCtx_reset(m_pCompressContext, ZSTD_reset_session_only);
	ZSTD_CCtx_setParameter(m_pCompressContext, ZSTD_c_compressionLevel, 3);
	ZSTD_CCtx_setParameter(m_pCompressContext, ZSTD_c_contentSizeFlag, 0);
	ZSTD_CCtx_setParameter(m_pCompressContext, ZSTD_c_checksumFlag, 0);
	ZSTD_CCtx_setParameter(m_pCompressContext, ZSTD_c_dictIDFlag, 0);

	size_t Result = ZSTD_compress2(m_pCompressContext, (unsigned char *) pOutput, (size_t) OutputSize, pInput, (size_t) InputSize);
	if(ZSTD_isError(Result))
		return -1;
	return (int) Result;
}

int CZstdDict::Decompress(const void *pInput, int InputSize, void *pOutput, int OutputSize)
{
	if(!m_pDecompressContext || InputSize <= 0 || OutputSize <= 0)
		return -1;

	ZSTD_DCtx_reset(m_pDecompressContext, ZSTD_reset_session_only);

	size_t Result = ZSTD_decompressDCtx(m_pDecompressContext, pOutput, (size_t) OutputSize, pInput, (size_t) InputSize);
	if(ZSTD_isError(Result))
		return -1;
	return (int) Result;
}
